function opening(launchedTokenIsQuote, tickSpacing = 60, overrides = {}) {
  return deriveLaunchPoolRecipe({ pairedTokenDecimals: 18, pairedTokenUsdPriceX18: 10n ** 18n,
    targetMarketCapUsdX18: 5_000n * 10n ** 18n, supply: SUPPLY, tokenBudget: SUPPLY / 2n,
    launchedTokenIsQuote, fee: 3000, tickSpacing, ...overrides });
}

function ranges(launchedTokenIsQuote, venue, distributionPreset, tokenBudget = SUPPLY / 2n + 3n, overrides = {}) {
  // Literal source-geometry tests intentionally disable the new default tail.
  return deriveLaunchPositionRanges({ launchSqrtPriceX96: Q96, launchedTokenIsQuote,
    tokenBudget, tickSpacing: 60, venue, distributionPreset, extendFinalRangeToBoundary: false, ...overrides });
}

// A single exact rational ceiling is independently equivalent to the Solidity
// SqrtPriceMath mint debit, including amount0's two successive ceiling divisions.
function mintDebit(liquidity, lower, upper, token0) {
  return token0 ? ceil(liquidity * Q96 * (upper - lower), lower * upper)
    : ceil(liquidity * (upper - lower), Q96);
}

function fundableLiquidity(cap, lower, upper, token0) {
  return token0 ? cap * lower * upper / (Q96 * (upper - lower))
    : cap * Q96 / (upper - lower);
}

function endpointGross(positions) {
  const gross = new Map();
  for (const { tickLower, tickUpper, liquidity } of positions) {
    gross.set(tickLower, (gross.get(tickLower) ?? 0n) + liquidity);
    gross.set(tickUpper, (gross.get(tickUpper) ?? 0n) + liquidity);
  }
  return gross;
}

