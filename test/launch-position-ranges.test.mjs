        const gross = endpointGross(result.positions);
        assert([...gross.values()].every((value) => value <= capacity));
        assert.equal(gross.get(0), result.positions[0].liquidity,
          "Only the first band's gross liquidity belongs to the opening endpoint");
        if (preset === "smooth-ramp") {
          assert.equal(gross.size, 6);
          for (let index = 0; index < 4; index += 1) {
            const sharedTick = token0 ? result.positions[index].tickUpper : result.positions[index].tickLower;
            assert.equal(gross.get(sharedTick), result.positions[index].liquidity + result.positions[index + 1].liquidity);
          }
        }
