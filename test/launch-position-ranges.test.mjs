test("two source-defined pool shares retain exact mint dust without charging the inventory twice", () => {
  const perPoolBudget = 1_000_003n;
  for (const token0 of [true, false]) {
    const recipe = opening(token0);
    const pools = [ranges(token0, "abyss", "smooth-ramp", perPoolBudget, { launchSqrtPriceX96: recipe.launchSqrtPriceX96 }),
      ranges(token0, "uniswap-v4", "staircase", perPoolBudget, { launchSqrtPriceX96: recipe.launchSqrtPriceX96 })];
    for (const pool of pools) {
      assert(pool.unspentTokenAmount > 0n);
      const expectedDebits = pool.positions.map((position) => mintDebit(position.liquidity,
        getSqrtRatioAtTick(position.tickLower), getSqrtRatioAtTick(position.tickUpper), token0));
      assert.deepEqual(pool.positions.map((position) => position.maxTokenAmount),
        pool.positions.map((position) => position.allocatedTokenAmount));
      assert.equal(pool.unspentTokenAmount, pool.positions.reduce((dust, position, index) =>
        dust + position.allocatedTokenAmount - expectedDebits[index], 0n));
      assert.equal(pool.tokenAmountMaximum, perPoolBudget);
      assert(pool.positions.some((position) => {
        const lower = getSqrtRatioAtTick(position.tickLower);
        const upper = getSqrtRatioAtTick(position.tickUpper);
        const numerator = token0 ? position.liquidity * Q96 * (upper - lower) : position.liquidity * (upper - lower);
        const denominator = token0 ? lower * upper : Q96;
        return numerator % denominator !== 0n && ceil(numerator, denominator) <= position.maxTokenAmount;
      }), "Fractional mint debits must round UP, not become unsafe floor maxima");
    }
    assert.equal(pools.reduce((total, pool) => total + pool.tokenAmountMaximum, 0n), 2n * perPoolBudget);
  }
});

