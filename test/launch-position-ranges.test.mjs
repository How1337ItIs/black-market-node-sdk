test("a later shared endpoint rejects gross overflow even when all individual mint liquidities fit", () => {
  const topology = TOPOLOGIES["smooth-ramp"];
  for (const venue of ["abyss", "uniswap-v4"]) {
    const capacity = MAX_UINT128 / (venue === "abyss" ? 29_575n : 29_576n);
    const budget = capacity / 18n;
    for (const token0 of [true, false]) {
      const ticks = token0 ? topology.token0 : topology.token1;
      let allocated = 0n;
      const expected = ticks.map(([tickLower, tickUpper], index) => {
        const cap = index === 4 ? budget - allocated : budget * BigInt(topology.weights[index]) / 10_000n;
        allocated += cap;
        return { tickLower, tickUpper, liquidity: fundableLiquidity(cap,
          getSqrtRatioAtTick(tickLower), getSqrtRatioAtTick(tickUpper), token0, venue) };
      });
      assert(expected.every((position) => position.liquidity < capacity && position.liquidity <= MAX_INT128));
      const gross = endpointGross(expected);
      const failingTick = token0 ? 3240 : -3240;
      assert(gross.get(failingTick) > capacity);
      assert([...gross.entries()].every(([tick, liquidity]) => tick === failingTick || liquidity <= capacity));
      assert.throws(() => ranges(token0, venue, "smooth-ramp", budget), new RegExp(`tick capacity at ${failingTick}`));
    }
  }
});

